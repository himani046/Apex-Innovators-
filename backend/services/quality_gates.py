"""Quality gates for evidence provenance and honest workflow completion."""
from __future__ import annotations

from typing import Any


AGENT_CONTRACTS = {
    "Odin": {"responsibility": "Orchestrate workflow, enforce budgets, and synthesize outputs", "consumes": ["agent_status", "agent_messages", "analysis_results"], "produces": ["workflow_status", "synthesis"]},
    "Thor": {"responsibility": "Extract candidate terms from contract source text", "consumes": ["contracts"], "produces": ["extracted_terms", "citations", "ambiguities"]},
    "Norns": {"responsibility": "Normalize dates, obligations, and timeline projections", "consumes": ["extracted_terms", "events", "as_of_date"], "produces": ["timeline_events"]},
    "Loki": {"responsibility": "Challenge interpretations and identify risk/evidence gaps", "consumes": ["extracted_terms", "timeline_events"], "produces": ["risk_claims", "clarification_requests"]},
    "Heimdall": {"responsibility": "Verify source citations and map evidence to claims/events", "consumes": ["risk_claims", "evidence_references", "events"], "produces": ["verification_outcomes", "unresolved_questions"]},
    "Tyr": {"responsibility": "Resolve agent disputes and draft bounded recommendations for human review", "consumes": ["risk_claims", "verification_outcomes", "unresolved_questions"], "produces": ["ruling", "recommended_actions"]},
}
MESSAGE_SCHEMA = {
    "required": ["from", "to", "type", "status"],
    "optional_common_fields": ["run_id", "iteration", "contract_id", "clause_id", "evidence_refs", "payload"],
    "version": "1.1",
}


def apply_analysis_quality(state: dict[str, Any], contracts: dict[str, str]) -> dict[str, Any]:
    """Verify every extracted candidate has a verbatim source citation and label provenance.

    The gate is conservative: any missing/invalid term citation, truncated extraction,
    or ingestion parse error makes the run explicitly partial instead of complete.
    """
    summary: dict[str, Any] = {
        "status": "passed",
        "terms_checked": 0,
        "verified_source_facts": 0,
        "unverified_or_uncited_terms": 0,
        "truncated_contracts": [],
        "parse_error_count": sum(
            len(items or []) for items in (state.get("event_summary", {}).get("parse_errors") or {}).values()
        ),
        "ambiguities": [],
        "provenance_rules": {
            "source_fact": "A candidate term with an exact quote found in the canonical contract text; this is not a legal conclusion.",
            "agent_analysis": "Risk scores, interpretations, recommendations, and projections generated by rules or agents; these are not source facts.",
            "unverified": "A term without a verified exact-source citation must not be treated as established evidence.",
        },
    }
    portfolio = state.get("portfolio_extraction") or {}
    by_contract = portfolio.get("contracts") or {}
    for contract_id, extraction in by_contract.items():
        if not isinstance(extraction, dict):
            summary["ambiguities"].append(f"{contract_id}: extraction result was malformed.")
            summary["unverified_or_uncited_terms"] += 1
            continue
        completeness = extraction.get("completeness") or {}
        if completeness.get("is_truncated"):
            summary["truncated_contracts"].append(contract_id)
        for ambiguity in extraction.get("ambiguities") or []:
            summary["ambiguities"].append({"contract_id": contract_id, "description": str(ambiguity)})
        for term in extraction.get("extracted_terms") or []:
            summary["terms_checked"] += 1
            if not isinstance(term, dict):
                summary["unverified_or_uncited_terms"] += 1
                continue
            citation = term.get("citation")
            quote = str((citation or {}).get("quote") or "") if isinstance(citation, dict) else ""
            source_id = str((citation or {}).get("document_id") or contract_id) if isinstance(citation, dict) else contract_id
            exact = bool(quote.strip()) and quote in str(contracts.get(source_id, ""))
            # Preserve citation metadata but recompute trust against canonical input.
            if isinstance(citation, dict):
                citation["verified"] = exact
                citation["verification_note"] = (
                    "Exact quote found in canonical source text."
                    if exact else "Quote missing or not found verbatim in canonical source; not verified."
                )
            term["provenance"] = "source_fact" if exact else "unverified"
            term["source_verified"] = exact
            term["analysis_note"] = "Keyword/topic classification and confidence are heuristic; this candidate is not a legal conclusion."
            if exact:
                summary["verified_source_facts"] += 1
            else:
                summary["unverified_or_uncited_terms"] += 1
    # The legacy A1 vertical slice is a separate Thor extraction path; gate it too.
    legacy = state.get("extraction") or {}
    if isinstance(legacy, dict):
        for ambiguity in legacy.get("ambiguities") or []:
            summary["ambiguities"].append({"contract_id": legacy.get("contract_id", "A1"), "description": str(ambiguity)})
        for term in legacy.get("extracted_terms") or []:
            summary["terms_checked"] += 1
            if not isinstance(term, dict):
                summary["unverified_or_uncited_terms"] += 1
                continue
            citation = term.get("citation")
            quote = str((citation or {}).get("quote") or "") if isinstance(citation, dict) else ""
            source_id = str((citation or {}).get("document_id") or legacy.get("contract_id") or "A1") if isinstance(citation, dict) else str(legacy.get("contract_id") or "A1")
            exact = bool(quote.strip()) and quote in str(contracts.get(source_id, ""))
            if isinstance(citation, dict):
                citation["verified"] = exact
                citation["verification_note"] = (
                    "Exact quote found in canonical source text."
                    if exact else "Quote missing or not found verbatim in canonical source; not verified."
                )
            term["provenance"] = "source_fact" if exact else "unverified"
            term["source_verified"] = exact
            term["analysis_note"] = "Agent summary/interpretation is analysis; only the cited exact excerpt is source evidence."
            if exact:
                summary["verified_source_facts"] += 1
            else:
                summary["unverified_or_uncited_terms"] += 1

    if summary["unverified_or_uncited_terms"] or summary["truncated_contracts"] or summary["parse_error_count"]:
        summary["status"] = "partial_review_required"
    summary["truncated_contracts"] = sorted(set(summary["truncated_contracts"]))
    summary["ambiguities"] = summary["ambiguities"][:200]
    state["analysis_quality"] = summary
    state["agent_architecture"] = {
        "pattern": "bounded state-machine workflow",
        "shared_state_schema_version": "1.1",
        "message_schema": MESSAGE_SCHEMA,
        "agents": AGENT_CONTRACTS,
        "provenance_policy": summary["provenance_rules"],
    }
    if summary["status"] != "passed":
        state.setdefault("limitations", []).append(
            "Evidence quality gate found uncited/unverified terms, truncated extraction, or event parse errors. This run is partial and requires review."
        )
        if state.get("status") in {"complete", "complete_with_limitations"}:
            state["status"] = "partial_quality_review_required"
    return summary
